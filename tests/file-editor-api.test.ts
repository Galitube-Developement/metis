import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync, existsSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import test from "node:test";

test("file editor API creates exclusively, reports conflicts, renames, saves and enforces workspace access", async () => {
  const root = mkdtempSync("/root/metis-file-editor-test-");
  Object.assign(process.env, { CHAT_DATA_DIR: root, CHAT_DB_PATH: path.join(root, "chat.sqlite"), AGENT_CWD: root, AI_CHAT_ALLOW_ROOT_AGENTS: "true", METIS_AI_BOOTSTRAP_PASSWORD: "", CHAT_LEGACY_HEADER_AUTH: "false" });
  const { createUser, authenticateUser } = await import("../lib/auth");
  const { getDatabase } = await import("../lib/sqlite");
  const { POST } = await import("../app/api/remote/route");
  const owner = createUser("file-editor-owner", "test-password");
  const other = createUser("file-editor-other", "test-password");
  const db = getDatabase();
  db.prepare("UPDATE users SET is_admin=1 WHERE id=?").run(owner.id);
  db.prepare("INSERT OR REPLACE INTO user_workspace_access(user_id,workspace_root,os_username,uid,gid,created_at,updated_at) VALUES(?,?,?,?,?,'test','test')").run(owner.id, root, "root", 0, 0);
  const token = authenticateUser("file-editor-owner", "test-password")!.token;
  const otherToken = authenticateUser("file-editor-other", "test-password")!.token;
  const call = (body: unknown, auth = token) => POST(new Request("http://localhost/api/remote", { method:"POST", headers: { "Content-Type":"application/json", ...(auth ? { cookie:"ai_chat_auth="+auth } : {}) }, body:JSON.stringify(body) }));
  const file = path.join(root, "Größe 'test'.yml");
  try {
    assert.equal((await call({ action:"create", path:file, cwd:root }, "")).status, 401);
    assert.equal((await call({ action:"create", path:file, cwd:root }, otherToken)).status, 403);
    assert.equal((await call({ action:"create", path:"/etc/escape", cwd:root })).status, 400);
    const nested = path.join(root, "plugins", "example");
    mkdirSync(nested, { recursive: true });
    writeFileSync(path.join(nested, "Config.yml"), "title: Example\nenabled: true\nEnabled: false\n");
    writeFileSync(path.join(nested, ".hidden.yml"), "enabled: hidden\n");
    const search = (query: string, searchMode = "files", extra = {}) => call({ action: "search", path:root, cwd:root, query, searchMode, ...extra });
    const files = await search("config");
    assert.equal(files.status, 200);
    assert.deepEqual((await files.json()).search.files.map((f: {path:string}) => f.path), ["plugins/example/Config.yml"]);
    const grep = await search("enabled", "content");
    assert.equal(grep.status, 200);
    const matches = (await grep.json()).search.matches;
    assert(matches.some((m:{path:string;line:number}) => m.path === "plugins/example/Config.yml" && m.line === 2));
    assert(matches.some((m:{path:string;line:number}) => m.path === "plugins/example/Config.yml" && m.line === 3));
    assert(matches.some((m:{path:string}) => m.path === "plugins/example/.hidden.yml"));
    const sensitive = (await (await search("Enabled", "content", { caseSensitive: true })).json()).search.matches;
    assert.equal(sensitive.length, 1);
    assert.equal(sensitive[0].line, 3);
    const regex = await search("^enabled: true$", "content", { regex: true });
    assert.equal((await regex.json()).search.matches.length, 1);
    for (const [query, searchMode, extra] of [["", "files", {}], ["x".repeat(501), "files", {}], ["[", "content", {regex:true}], ["x", "other", {}], ["x", "content", {caseSensitive:"yes"}]] as const) assert.equal((await search(query, searchMode, extra)).status, 400);
    assert.equal((await call({ action:"search", path:"/etc", cwd:root, query:"secret", searchMode:"content" })).status, 400);
    assert.equal((await call({ action:"search", path:root, cwd:root, query:"enabled", searchMode:"content" }, otherToken)).status, 403);
    const glob = await search("*.yml");
    assert((await glob.json()).search.files.length >= 2);
    const created = await call({ action:"create", path:file, cwd:root });
    assert.equal(created.status, 200, await created.text());
    assert.equal(readFileSync(file, "utf8"), "");
    writeFileSync(file, "keep this");
    assert.equal((await call({ action:"create", path:file, cwd:root })).status, 502);
    assert.equal(readFileSync(file, "utf8"), "keep this");
    const folder = path.join(root, "New folder");
    assert.equal((await call({ action:"mkdir", path:folder, cwd:root })).status, 200);
    assert.equal((await call({ action:"mkdir", path:folder, cwd:root })).status, 502);
    const conflict = path.join(root, "conflict.yml"); writeFileSync(conflict, "existing");
    assert.equal((await call({ action:"rename", path:file, newPath:conflict, cwd:root })).status, 502);
    assert.equal(readFileSync(file, "utf8"), "keep this");
    assert.equal(readFileSync(conflict, "utf8"), "existing");
    const renamed = path.join(root, "renamed.yml");
    assert.equal((await call({ action:"rename", path:file, newPath:renamed, cwd:root })).status, 200);
    assert.equal(existsSync(file), false);
    assert.equal((await call({ action:"write", path:renamed, content:"enabled: true\n", cwd:root })).status, 200);
    const snap = await call({action:"snapshot",path:renamed,cwd:root});
    assert.equal(snap.status,200);const snapshot=await snap.json();assert.equal(snapshot.content,"enabled: true\n");
    assert.equal((await call({action:"snapshot",path:renamed,cwd:root,revision:snapshot.revision})).status,200);
    writeFileSync(renamed,"external disk edit\n");
    const stale=await call({action:"save",path:renamed,cwd:root,revision:snapshot.revision,content:"draft\n"});
    assert.equal(stale.status,409);const diskConflict=await stale.json();assert.equal(diskConflict.content,"external disk edit\n");
    assert.equal((await call({action:"save",path:renamed,cwd:root,revision:diskConflict.revision,content:"enabled: true\n"})).status,200);
    assert.equal((await call({action:"save",path:renamed,cwd:root,content:"no revision"})).status,400);
    assert.equal((await call({action:"snapshot",path:renamed,cwd:root},otherToken)).status,403);
    const read = await call({ action:"read", path:renamed, cwd:root });
    assert.equal(read.status, 200);
    assert.equal((await read.json()).content.trim(), "enabled: true");
    assert.equal((await call({ action:"delete", path:renamed, cwd:root })).status, 200);
    assert.equal(existsSync(renamed), false);
    assert.equal((await call({ action:"mkdir", path:path.join(root,"missing","child"), cwd:root })).status, 502);
  } finally { db.close(); rmSync(root, { recursive:true, force:true }); }
});
