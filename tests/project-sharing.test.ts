test("authenticated project and inbox APIs enforce membership and target identity",async()=>{
 const [auth,,,,sharing]=modules;
 const membersRoute=await import("../app/api/projects/[id]/members/route");
 const inviteRoute=await import("../app/api/project-invitations/[id]/route");
 const inboxRoute=await import("../app/api/notifications/inbox/route");
 const projectRoute=await import("../app/api/projects/[id]/route");
 const tokens={
  owner:auth.authenticateUser("project-owner","password123")!.token,
  member:auth.authenticateUser("project-member","password123")!.token,
  stranger:auth.authenticateUser("stranger","password123")!.token
 };
 const req=(url:string,token?:string,body?:unknown)=>new Request("http://localhost"+url,{method:body ? "POST" : "GET",headers:{...(token?{cookie:"ai_chat_auth="+token}:{}),...(body?{"Content-Type":"application/json"}:{})},...(body?{body:JSON.stringify(body)}:{})});
 const context={params:Promise.resolve({id:projectId})};
 assert.equal((await membersRoute.GET(req("/api/projects/"+projectId+"/members"),context)).status,401);
 assert.equal((await membersRoute.GET(req("/api/projects/"+projectId+"/members",tokens.stranger),context)).status,404);
 assert.equal((await membersRoute.POST(req("/api/projects/"+projectId+"/members",tokens.member,{username:"stranger"}),context)).status,403);
 const shared=await projectRoute.GET(req("/api/projects/"+projectId,tokens.member),context);
 assert.equal(shared.status,200);
 const body=await shared.json();
 assert.equal(body.project.membershipRole,"member");
 assert.ok(body.notes.some((n:{id:string})=>n.id===noteId));
 assert.ok(body.chats.some((c:{id:string})=>c.id===chatId));
 assert.equal((await projectRoute.GET(req("/api/projects/"+projectId,tokens.stranger),context)).status,404);
 const notification=(sharing.notificationInbox(member).notifications[0] as {id:string}).id;
 const read=await inboxRoute.POST(req("/api/notifications/inbox",tokens.stranger,{ids:[notification]}));
 assert.equal(read.status,200);
 assert.equal((await inboxRoute.GET(req("/api/notifications/inbox"))).status,401);
 const foreign=await inviteRoute.POST(req("/api/project-invitations/"+invitationId,tokens.stranger,{action:"accept"}),{params:Promise.resolve({id:invitationId})});
 assert.equal(foreign.status,404);
});
test("project runs retain the initiating account and its personal model and mode",async()=>{
 const [,projects,chats,,,sqlite]=modules;
 const {modelKey}=await import("../lib/providers/types");
 const {projectModelOverride}=await import("../lib/project-model-server");
 const jobs=await import("../lib/db-jobs");
 const db=sqlite.getDatabase();
 const models=new Map<string,string>();
 for(const user of [owner,member]){
  const connection="connection-"+user;
  db.prepare("INSERT INTO provider_connections(id,owner_id,provider_key,slug,label,auth_type,config,enabled,created_at,updated_at) VALUES (?,?, 'openai',?,'Fixture','api_key','{}',1,datetime('now'),datetime('now'))").run(connection,user,connection);
  db.prepare("INSERT INTO provider_models(connection_id,canonical_id,display_name,capabilities,discovered_at) VALUES (?,'model','Model','{}',datetime('now'))").run(connection);
  models.set(user,modelKey("openai","model",connection));
 }
 const p=projects.createProject({ownerId:owner,mode:"agents",name:"Shared team",defaultModelEnabled:true,defaultModelId:models.get(owner)});
 const invitation=modules[4].inviteProjectMember(p.id,owner,"project-member");
 modules[4].respondProjectInvitation(invitation.id,member,"accept");
 assert.equal(projectModelOverride(p.id,member),null);
 assert.throws(()=>projects.updateProject(p.id,{defaultModelEnabled:true,defaultModelId:models.get(owner)},member));
 projects.updateProject(p.id,{defaultModelEnabled:true,defaultModelId:models.get(member)},member);
 assert.equal(projectModelOverride(p.id,owner)?.modelId,models.get(owner));
 assert.equal(projectModelOverride(p.id,member)?.modelId,models.get(member));
 const team=await import("../lib/project-team");
 const agent=team.createProjectAgent({ownerId:owner,projectId:p.id,name:"Reviewer",role:"Review"});
 chats.updateChat(agent.chatId,{sessionState:{modeId:"plan",input:"Owner input"}},owner);
 chats.updateChat(agent.chatId,{sessionState:{modeId:"ask",input:"Member input"}},member);
 const job=jobs.enqueueJob({chatId:agent.chatId,userId:member,message:"Review together"});
 assert.equal(job.userId,member);
 assert.equal(job.modelId,models.get(member));
 assert.equal(job.modeId,"ask");
 assert.equal(chats.getChat(agent.chatId,owner)?.sessionState?.modeId,"plan");
 jobs.requestJobCancel(agent.chatId,member);
 const prompt=await import("../lib/providers/prompt-context");
 const built=prompt.buildProviderPrompt({job});
 assert.match(built,/Current agent mode: Ask/);
 assert.match(built,/Shared team/);
});
test("revoke, decline, re-invite and removal are immediate and cannot be replayed",()=>{
 const [,projects,chats,notes,sharing]=modules;
 const invited=sharing.inviteProjectMember(projectId,owner,"stranger");
 sharing.removeProjectMember(projectId,owner,{invitationId:invited.id});
 assert.throws(()=>sharing.respondProjectInvitation(invited.id,stranger,"accept"));
 const again=sharing.inviteProjectMember(projectId,owner,"stranger");
 assert.equal(sharing.respondProjectInvitation(again.id,stranger,"decline").status,"declined");
 assert.equal(projects.getProject(projectId,stranger),null);
 const stale=chats.getChat(chatId,member)!;
 const memberNote=notes.createNote({ownerId:member,projectId,title:"Member note",content:"Project content"});
 sharing.removeProjectMember(projectId,owner,{userId:member});
 assert.throws(()=>chats.saveChat({...stale,title:"Stale write"}),/revoked/);
 assert.equal(notes.getNote(memberNote.id,member),null);
 assert.ok(notes.getNote(memberNote.id,owner));
 assert.equal(projects.getProject(projectId,member),null);
 assert.equal(chats.getChat(chatId,member),null);
 assert.equal(chats.getChatPage(chatId,member,10,0),null);
 assert.equal(chats.getChat(memberChatId,member),null);
 assert.ok(!chats.listChatsForUser(member).some(c=>c.id===memberChatId));
 assert.equal(notes.getNote(noteId,member),null);
 assert.throws(()=>sharing.respondProjectInvitation(invitationId,member,"accept"),"An accepted historical invitation must not restore removed membership");
});
test("account inbox excludes historical and new run completions without hiding invitations or changing delivery feeds",async()=>{
 const [auth,,,,sharing]=modules;
 const store=await import("../lib/notification-store");
 const user=auth.createUser("inbox-recipient","password123").id;
 const completion=(id:string)=>store.createNotification(user,{title:"Run completed"},"run:"+user+":done:"+id);
 completion("historical");
 assert.equal(sharing.notificationInbox(user).unreadCount,0);
 assert.deepEqual(sharing.notificationInbox(user).notifications,[]);
 const failed=store.createNotification(user,{title:"Run failed"},"run:"+user+":error:failed");
 const custom=store.createNotification(user,{title:"Run completed"});
 const invite=sharing.inviteProjectMember(projectId,owner,"inbox-recipient");
 // A page full of newer completions must not crowd out actionable notifications.
 for(let i=0;i<120;i++)completion("new-"+i);
 const inbox=sharing.notificationInbox(user);
 assert.equal(inbox.unreadCount,3);
 assert.equal(inbox.notifications.length,3);
 assert.ok(inbox.notifications.some(n=>n.invitationId===invite.id && n.invitationStatus==="pending"));
 assert.ok(inbox.notifications.some(n=>n.id===failed.id));
 assert.ok(inbox.notifications.some(n=>n.id===custom.id),"Custom notifications are not classified by their display title");
 const feed=store.getNotificationFeed(user,0);
 assert.ok(feed.notifications.length>inbox.notifications.length,"OS/browser delivery feed retains completion events");
 assert.ok(feed.notifications.some(n=>n.title==="Run completed" && n.id!==custom.id));
 const api=await import("../app/api/notifications/inbox/route");
 const token=auth.authenticateUser("inbox-recipient","password123")!.token;
 const response=await api.GET(new Request("http://localhost/api/notifications/inbox",{headers:{cookie:"ai_chat_auth="+token}}));
 assert.equal(response.status,200);
 assert.equal((await response.json()).unreadCount,3);
 sharing.markNotificationsRead(user,[failed.id,custom.id]);
 assert.equal(sharing.notificationInbox(user).unreadCount,1);
 sharing.markNotificationsRead(user,null);
 completion("after-read");
 assert.equal(sharing.notificationInbox(user).unreadCount,0,"Hidden completions cannot light the avatar badge");
 assert.equal(sharing.notificationInbox(user).notifications.length,3);
 assert.ok(!sharing.notificationInbox(stranger).notifications.some(n=>n.id===failed.id));
});
