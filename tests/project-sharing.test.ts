import {mkdtempSync,rmSync} from "node:fs";
import os from "node:os";
import path from "node:path";
import test,{before,after} from "node:test";
const root=mkdtempSync(path.join(os.tmpdir(),"metis-project-sharing-"));
Object.assign(process.env,{AI_CHAT_ROOT:root,CHAT_DATA_DIR:root,CHAT_DB_PATH:path.join(root,"chat.sqlite"),AGENT_CWD:root,CHAT_PASSWORD:"",METIS_AI_BOOTSTRAP_PASSWORD:"",CHAT_LEGACY_HEADER_AUTH:"false"});
const imports=Promise.all([import("../lib/auth"),import("../lib/projects"),import("../lib/db-store"),import("../lib/shared-context"),import("../lib/project-sharing"),import("../lib/sqlite"),import("../lib/project-access"),import("../lib/chat-sync")]);
let modules:Awaited<typeof imports>;
let owner:string,member:string,stranger:string,projectId:string,invitationId:string,chatId:string,noteId:string,memberChatId:string;
before(async()=>{
 modules=await imports;
 const [auth,projects,chats,notes]=modules;
 owner=auth.createUser("project-owner","password123").id;
 member=auth.createUser("project-member","password123").id;
 stranger=auth.createUser("stranger","password123").id;
 const project=projects.createProject({ownerId:owner,name:"Shared launch",instructions:"Project instructions"});
 projectId=project.id;
 chatId=chats.createChat("Planning",undefined,owner,{id:"owner-provider/model"},{projectId}).id;
 chats.updateChat(chatId,{sessionState:{modeId:"owners-custom-mode",input:"owner draft"}},owner);
 chats.appendMessage(chatId,{id:"msg-one",role:"user",content:"Shared transcript"},owner);
 noteId=notes.createNote({ownerId:owner,projectId,title:"Release checklist",content:"Shared note"}).id;
 projects.createProjectMemory(projectId,"Shared memory",[],owner);
});
