test("API totals, days, models, details, filters and CSV use the same separate counters",async()=>{
 const {createUser}=await import("../lib/auth");
 const {recordAccountUsage,getAccountUsage,getAccountModelUsage}=await import("../lib/account-usage");
 const owner=createUser("split-owner","synthetic-pass-123"),other=createUser("split-other","synthetic-pass-123");
 const record=(id:string,meta:Record<string,unknown>,ownerId=owner.id)=>recordAccountUsage(ownerId,{id,role:"assistant",runMetadata:{modelId:"fixture",completedAt:"2026-10-01T12:00:00Z",...meta}});
 const codex={providerId:"codex",inputTokens:1000,outputTokens:50,cachedInputTokens:900,cacheWriteInputTokens:20};
 record("codex",codex);record("codex",codex);
 record("claude",{providerId:"claude-code",inputTokens:80,outputTokens:50,cachedInputTokens:900,cacheWriteInputTokens:20,totalTokens:130});
 record("cursor",{providerId:"cursor",inputTokens:400,outputTokens:10});
 record("foreign",codex,other.id);
 const result=getAccountUsage(owner.id,"2026-10-01","2026-10-02");
 assert.equal(result.totals.requests,3);
 assert.equal(result.totals.uncachedInputTokens,560);
 assert.equal(result.totals.cachedInputTokens,1800);
 assert.equal(result.totals.cacheWriteInputTokens,40);
 assert.equal(result.totals.outputTokens,110);
 assert.equal(result.totals.unclassifiedInputTokens,0);
 assert.equal(result.totals.tokens,2510);
 assert.equal(result.totals.uncachedInputReports,3);assert.equal(result.totals.cachedInputReports,2);
 assert.equal(result.days[0].cachedInputTokens,1800);assert.equal(result.days[1].cachedInputTokens,0);
 const model=getAccountModelUsage(owner.id,"codex","fixture","2026-10-01","2026-10-02")!;
 assert.equal(model.uncachedInputTokens,80);assert.equal(model.days[0].cacheWriteInputTokens,20);
 assert.equal(getAccountUsage(owner.id,"2026-10-01","2026-10-02",null,["codex"]).totals.cachedInputTokens,900);
 const contribution=usageModelContributions(result.days[0],result.modelDays!["2026-10-01"],"cachedInputTokens","hidden");
 assert.equal(contribution.total,1800);assert.equal(contribution.partial,true);
 assert.equal(contribution.rows.find(x=>x.providerId==="codex")!.percentage,50);
 assert.equal(contribution.rows.find(x=>x.providerId==="cursor")!.value,null);
 const csv=usageCsv([model],"hidden");
 const [header,row]=csv.split("\r\n").map(line=>line.split(",").map(cell=>cell.slice(1,-1)));
 assert.equal(row[header.indexOf("Input (uncached)")],"80");
 assert.equal(row[header.indexOf("Cached input tokens")],"900");
 assert.equal(row[header.indexOf("Cache write tokens")],"20");
});
test("upsert retains missing cache only for the same input measurement",async()=>{
 const {createUser}=await import("../lib/auth"),{getDatabase}=await import("../lib/sqlite");
 const {recordAccountUsage}=await import("../lib/account-usage");
 const owner=createUser("split-upsert","synthetic-pass-123");
 const meta={providerId:"codex",modelId:"fixture",inputTokens:100,outputTokens:5,cachedInputTokens:90,cacheWriteInputTokens:0,completedAt:"2026-10-01T12:00:00Z"};
 const record=(runMetadata:NonNullable<Parameters<typeof recordAccountUsage>[1]["runMetadata"]>)=>recordAccountUsage(owner.id,{id:"run",role:"assistant",runMetadata});
 record(meta);record({...meta,cachedInputTokens:undefined,cacheWriteInputTokens:undefined});
 const select=()=>getDatabase().prepare("SELECT * FROM account_usage WHERE owner_id=? AND message_id='run'").get(owner.id)!;
 assert.equal(select().cached_input_tokens,90);
 record({...meta,inputTokens:10,cachedInputTokens:undefined,cacheWriteInputTokens:undefined});
 assert.equal(select().cached_input_tokens,null);assert.equal(select().cache_write_input_tokens,null);
});
