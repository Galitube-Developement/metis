import assert from "node:assert/strict";
import test from "node:test";
import { mkdtempSync,rmSync } from "node:fs";
import os from "node:os";
import path from "node:path";
const root=mkdtempSync(path.join(os.tmpdir(),"metis-antigravity-contract-"));
Object.assign(process.env,{CHAT_DATA_DIR:root,CHAT_DB_PATH:path.join(root,"db.sqlite"),AGENT_CWD:root,AI_CHAT_ROOT:root,AI_CHAT_SECRETS_KEY:"00".repeat(32)});
test.after(()=>rmSync(root,{recursive:true,force:true}));
test("Antigravity discards stale inferred options, persists live contracts and validates saved parameters",async()=>{
 const {getDatabase}=await import("../lib/sqlite");
 const {upsertProviderConnection,saveProviderModels}=await import("../lib/provider-connections");
 const {providerModelsForConnection,parseDiscoveredModel,persistDiscoveredModels}=await import("../lib/providers/discovery");
 const {sanitizeModelParams}=await import("../lib/model-params");
 const {getProviderModelDefinition}=await import("../lib/providers/registry");
 const db=getDatabase(),stamp=new Date().toISOString();
 db.prepare("INSERT INTO users VALUES(?,?,?,?,0)").run("owner","owner","unused",stamp);
 const connection=upsertProviderConnection("owner",{providerKey:"antigravity",slug:"test",label:"Test",authType:"oauth",secret:"fixture"})!;
 const stale={id:"gemini-3.6-flash",displayName:"Gemini",parameters:[{id:"effort",values:[{value:"medium"}]}],defaultParams:[{id:"effort",value:"medium"}]};
 saveProviderModels(connection.id,[stale]);
 let resolved=providerModelsForConnection({...connection,secret:"fixture"})[0];
 assert.equal(resolved.parameters?.length,0);
 assert.deepEqual(sanitizeModelParams({parameters:resolved.parameters?.map(p=>({...p,values:[...p.values]}))},[{id:"effort",value:"medium"}]),[]);
 const live=parseDiscoveredModel({id:"future-model",displayName:"Future",parameters:[{id:"effort",values:[{value:"high"}]}]})!;
 persistDiscoveredModels(connection.id,[live]);
 resolved=providerModelsForConnection({...connection,secret:"fixture"})[0];
 assert.equal(resolved.parameterSource,"provider");
 const contract={parameters:resolved.parameters?.map(p=>({...p,values:[...p.values]}))};
 assert.deepEqual(sanitizeModelParams(contract,[{id:"effort",value:"medium"}]),[]);
 assert.deepEqual(sanitizeModelParams(contract,[{id:"effort",value:"high"},{id:"context",value:"max"}]),[{id:"effort",value:"high"}]);
 assert.equal(getProviderModelDefinition("antigravity","gemini-unknown-future"),undefined);
 persistDiscoveredModels(connection.id,[{id:"future-model",displayName:"No options"}]);
 assert.deepEqual(providerModelsForConnection({...connection,secret:"fixture"})[0].parameters,[]);
});
